// фаза и её человекочитаемое описание
function ensoPhase(oni) {
  if (oni >= 0.5) return { key: 'el', sign: 1, mag: oni };
  if (oni <= -0.5) return { key: 'la', sign: -1, mag: -oni };
  return { key: 'neutral', sign: 0, mag: 0 };
}
function ensoStrength(mag) {
  if (mag >= 2.0) return 'очень сильное';
  if (mag >= 1.5) return 'сильное';
  if (mag >= 1.0) return 'умеренное';
  if (mag >= 0.5) return 'слабое';
  return 'нейтрально';
}
function ensoLabel(oni) {
  const p = ensoPhase(oni);
  if (p.key === 'neutral') return 'Нейтральная фаза (ни Эль-Ниньо, ни Ла-Нинья)';
  const name = p.key === 'el' ? 'Эль-Ниньо' : 'Ла-Нинья';
  return `${name} · ${ensoStrength(p.mag)} (ONI ${oni > 0 ? '+' : ''}${oni.toFixed(1)})`;
}

if (typeof module !== 'undefined') module.exports = { ONI, ONI_YEARS, ensoPhase, ensoLabel };
