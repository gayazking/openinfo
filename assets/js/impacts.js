/**
 * Рассчитать состояние страны при заданном ONI.
 * @returns { score(0-100), level(0-4), phaseKey, hazards:[{e,t,w}], goods:[{e,t}], note }
 */
function countryState(name, oni) {
  const prof = PROFILES[name];
  const phase = ensoPhase(oni); // {key, sign, mag}
  const base = prof ? prof.base : 3;
  if (phase.key === 'neutral') {
    return { score: Math.round(base * 0.5), level: levelOf(base * 0.5), phaseKey: 'neutral',
             hazards: [], goods: [], note: prof ? 'Нейтральная фаза — без выраженной аномалии ENSO.' : '', continent: prof ? prof.c : null };
  }
  const block = prof ? prof[phase.key] : null;
  if (!block || !block.hz.length) {
    const s = Math.round(base * (0.4 + 0.2 * phase.mag));
    return { score: clamp(s), level: levelOf(s), phaseKey: phase.key, hazards: [], goods: [],
             note: prof ? (block && block.note) || '' : '', continent: prof ? prof.c : null };
  }
  let raw = base * 0.6;
  const hazards = block.hz.map(([t, w]) => ({ e: HAZARDS[t].e, t: HAZARDS[t].t, w: w * phase.mag }))
                          .sort((a, b) => b.w - a.w);
  hazards.forEach(h => { raw += h.w; });
  const goods = (block.g || []).map(code => ({ e: GOODS[code].e, t: GOODS[code].t }));
  if (goods.length) raw -= 4; // позитив немного гасит
  const score = clamp(Math.round(raw));
  return { score, level: levelOf(score), phaseKey: phase.key,
           hazards: hazards.filter(h => h.w >= 4).slice(0, 4),
           goods, note: block.note, continent: prof.c };
}

function clamp(x) { return Math.max(0, Math.min(100, x)); }

